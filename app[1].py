
import streamlit as st
import pickle
import pandas as pd
import numpy as np

st.set_page_config(
    page_title="Patient Mortality Prediction",
    page_icon="🏥",
    layout="centered"
)

# Load model
with open("mortality_app/final_logistic_regression_model.pkl", "rb") as f:
    model = pickle.load(f)

# Load feature configuration
with open("mortality_app/model_features.pkl", "rb") as f:
    model_features = pickle.load(f)

st.title("🏥 Patient Mortality Prediction")
st.write("Predict patient mortality using demographic and clinical characteristics.")

st.subheader("Patient Information")

age = st.number_input(
    "Age in years",
    min_value=0,
    max_value=131,
    value=30
)

sex = st.selectbox(
    "Sex",
    options=[0, 1],
    format_func=lambda x: "Male" if x == 0 else "Female"
)

# Create empty feature vector
input_data = pd.DataFrame(
    np.zeros((1, len(model_features))),
    columns=model_features
)

# Set numerical features
if "Age in years" in input_data.columns:
    input_data["Age in years"] = age

if "sex" in input_data.columns:
    input_data["sex"] = sex

# Detect categorical feature groups
categorical_groups = {}

for feature in model_features:
    if "_" in feature:
        prefix, value = feature.split("_", 1)

        if prefix in [
            "CODES",
            "Diagnosis_Details",
            "Major group",
            "Year",
            "Year of occurrence",
            "Agegroup",
            "Diagnosis_broad",
            "Code",
            "Month_Occurance"
        ]:
            categorical_groups.setdefault(prefix, []).append(value)

# Create selection boxes
selected_values = {}

for group, values in categorical_groups.items():
    selected_values[group] = st.selectbox(
        group.replace("_", " "),
        sorted(values)
    )

# Set selected one-hot features to 1
for group, selected_value in selected_values.items():
    feature_name = f"{group}_{selected_value}"

    if feature_name in input_data.columns:
        input_data[feature_name] = 1

st.divider()

if st.button("Predict Mortality", type="primary"):

    prediction = model.predict(input_data)[0]

    probability = model.predict_proba(input_data)[0]

    if prediction == 1:
        st.error("⚠️ Prediction: DEAD")
        st.write(f"Probability of mortality: {probability[1] * 100:.2f}%")
    else:
        st.success("✅ Prediction: ALIVE")
        st.write(f"Probability of mortality: {probability[1] * 100:.2f}%")

    st.caption(
        "This prediction is generated by a machine-learning model "
        "and should not replace professional clinical judgment."
    )
